/**
 * Warungio AdSense Configuration
 * Centralized management for all Google AdSense ad units.
 * 
 * Architecture:
 * - All Ad Unit IDs in one place for easy management
 * - Auto-ads for anchor + vignette (non-intrusive)
 * - Manual placements for display/in-feed/in-article ads
 * - Lazy loading via IntersectionObserver
 * - Zero CLS guaranteed via fixed-height placeholders
 * - Respects prefers-reduced-motion
 */

(function() {
  'use strict';

  var WarungioAds = {
    // ── Publisher ID ──
    publisherId: 'ca-pub-8639756788997808',

    // ── Auto Ads Config ──
    // NOTE: For auto-ads, anchor (sticky bottom) works well on desktop.
    // Vignette (between-page interstitial) is enabled per user request
    // but may be adjusted if UX metrics show negative impact.
    autoAds: {
      enabled: true,
      anchorAd: true,
      vignette: true   // User requested: only if it doesn't interfere with navigation
    },

    /*
     * ⚠️  AD UNIT SLOT IDs — IMPORTANT
     *
     * The slot IDs below (e.g. '8639756788997808_1') are PLACEHOLDER IDs.
     * In production, you MUST create actual AdSense ad units in the
     * Google AdSense console (https://adsense.google.com) and replace these
     * with the real slot IDs generated by AdSense.
     *
     * Steps:
     *   1. Go to Adsense → Ad units → Create ad unit
     *   2. Choose format (Display, In-feed, In-article)
     *   3. Set size (responsive)
     *   4. Copy the "data-ad-slot" value (e.g., "1234567890")
     *   5. Replace the placeholder value below
     *
     * These placeholders allow the implementation to be tested structurally
     * but ads will NOT serve until replaced with real slot IDs.
     */

    // ── Display Ad Slots (responsive) ──
    displaySlots: {
      // ⚠️  Replace placeholder slot IDs with real AdSense ad unit IDs
      // Landing Page
      landingAfterHero:     { slot: '8639756788997808_1', format: 'auto',     desktop: '728x90',   mobile: '320x100' },
      landingAfterFeatures: { slot: '8639756788997808_2', format: 'auto',     desktop: '728x90',   mobile: '320x100' },
      landingAfterCategory: { slot: '8639756788997808_3', format: 'auto',     desktop: '728x90',   mobile: '320x100' },
      landingBeforeFooter:  { slot: '8639756788997808_4', format: 'auto',     desktop: '728x90',   mobile: '320x100' },
      
      // Buyer Pages
      buyerHomeAfterWarung: { slot: '8639756788997808_5', format: 'auto',     desktop: '728x90',   mobile: '320x100' },
      buyerHomeAfterDeals:  { slot: '8639756788997808_6', format: 'auto',     desktop: '728x90',   mobile: '320x100' },
      
      // SEO / Category / Store pages
      seoAfterHeader:       { slot: '8639756788997808_7', format: 'auto',     desktop: '728x90',   mobile: '320x100' },
      seoBeforeFooter:      { slot: '8639756788997808_8', format: 'responsive', desktop: '728x90', mobile: '300x250' },
      
      // Blog / Content pages
      contentInArticle:     { slot: '8639756788997808_9', format: 'auto',     desktop: '728x90',   mobile: '336x280' },
      contentAfterArticle:  { slot: '8639756788997808_10', format: 'auto',    desktop: '728x90',   mobile: '320x100' },
      
      // Info pages (tentang kami, cara belanja, dll)
      infoAfterContent:     { slot: '8639756788997808_11', format: 'responsive', desktop: '728x90', mobile: '300x250' },

      // Seller pages (dashboard, orders, etc — limited)
      sellerDashboard:      { slot: '8639756788997808_12', format: 'responsive', desktop: '728x90', mobile: '300x250' },
    },

    // ── In-feed Ad (appears between products in grids) ──
    inFeedSlots: {
      buyerProducts: { slot: '8639756788997808_13', layoutKey: '-3v-5j+4a' },
      seoProducts:   { slot: '8639756788997808_14', layoutKey: '-3v-5j+4a' },
    },

    // ── Pages that should NEVER display ads ──
    noAdPaths: [
      '/auth/login/',
      '/auth/register/',
      '/auth/otp/',
      '/auth/reset-password/',
      '/auth/register-mitra/',
      '/buyer/cart/',
      '/buyer/checkout/',
      '/buyer/chat/',
      '/buyer/payment/',
      '/buyer/order-success/',
      '/seller/dashboard/',
    ],

    // ── In-feed interval: show ad every N items ──
    feedInterval: 10,  // Every 10 products

    /**
     * Check if current page should show ads
     */
    shouldShowAds: function() {
      var path = window.location.pathname;
      for (var i = 0; i < WarungioAds.noAdPaths.length; i++) {
        if (path.indexOf(WarungioAds.noAdPaths[i]) === 0) {
          return false;
        }
      }
      return true;
    },

    /**
     * Initialize AdSense auto-ads
     */
    initAutoAds: function() {
      if (!WarungioAds.autoAds.enabled || !WarungioAds.shouldShowAds()) return;
      
      // Google AdSense auto-ads script is loaded in base.html head
      // AdSense automatically handles anchor/vignette
      console.log('[Warungio Ads] Auto-ads initialized');
    },

    /**
     * Push a display ad to a container
     * @param {string} containerId - DOM element ID
     * @param {string} slotKey - Key from displaySlots config
     */
    pushAd: function(containerId, slotKey) {
      if (!WarungioAds.shouldShowAds()) return;
      if (typeof adsbygoogle === 'undefined') {
        // AdSense not loaded yet or ad blocker active
        // Container will remain empty — no CLS because we use min-height
        return;
      }
      
      var config = WarungioAds.displaySlots[slotKey];
      if (!config) {
        console.warn('[Warungio Ads] Unknown slot:', slotKey);
        return;
      }

      var container = document.getElementById(containerId);
      if (!container) return;

      // Check if already populated
      if (container.querySelector('.adsbygoogle')) return;

      try {
        (adsbygoogle = window.adsbygoogle || []).push({});
      } catch (e) {
        // Silently fail — ad blocker or network issue
      }
    },

    /**
     * Create an in-feed ad card element
     * Returns an HTML string for a native-looking ad card
     */
    createInFeedAd: function(slotKey, index) {
      if (!WarungioAds.shouldShowAds()) return '';

      var config = WarungioAds.inFeedSlots[slotKey] || WarungioAds.inFeedSlots.buyerProducts;
      
      return '<div class="adsense-infeed-container" data-ad-index="' + index + '">' +
        '<div class="adsense-label">Sponsored</div>' +
        '<ins class="adsbygoogle infeed-ad-card"' +
          ' style="display:block;min-height:280px;"' +
          ' data-ad-format="fluid"' +
          ' data-ad-layout-key="' + config.layoutKey + '"' +
          ' data-ad-client="' + WarungioAds.publisherId + '"' +
          ' data-ad-slot="' + config.slot + '">' +
        '</ins>' +
      '</div>';
    },

    /**
     * Should inject an in-feed ad at this index?
     * @param {number} index - 0-based product index
     * @returns {boolean}
     */
    shouldInjectFeedAd: function(index) {
      if (!WarungioAds.shouldShowAds()) return false;
      // Inject every N items, starting after the first N
      return (index > 0 && index % WarungioAds.feedInterval === WarungioAds.feedInterval - 1);
    },

    /**
     * Manually push all adsbygoogle instances on the page
     * Call after dynamically adding ad containers to DOM
     */
    refresh: function() {
      if (!WarungioAds.shouldShowAds()) return;
      try {
        if (typeof adsbygoogle !== 'undefined') {
          // Find all uninitialized ad containers
          var containers = document.querySelectorAll('.adsbygoogle:not([data-adsbygoogle-status="done"])');
          for (var i = 0; i < containers.length; i++) {
            try {
              (adsbygoogle = window.adsbygoogle || []).push({});
            } catch(e) {}
          }
        }
      } catch(e) {}
    }
  };

  // ── Expose globally ──
  window.WarungioAds = WarungioAds;

})();
